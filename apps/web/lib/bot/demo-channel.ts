/**
 * Демо-идентификатор аккаунта канала (симулятор каналов, BRIEF v3).
 *
 * ЗАЧЕМ: сценарии каналов должны быть проходимы жюри end-to-end без
 * реальных токенов ботов (BRIEF v3 допускает демо-режим с честной
 * пометкой). Симулятор на странице /channels действует от СЕССИИ
 * пользователя, но через ТОТ ЖЕ handleBotCommand, что и живой бот, —
 * значит, ему нужен идентификатор аккаунта канала (channelUserId), какой
 * прислал бы провайдер.
 *
 * ПОЧЕМУ ИМЕННО ТАК (детерминированно, а не случайно):
 * - формат demo-<канал>-<userId> выводится из сессии и от внешних данных
 *   не зависит: один и тот же пользователь всегда попадает в один и тот
 *   же «аккаунт канала», привязка (/link) переживает перезагрузку
 *   страницы и работает из любого места кабинета;
 * - идентификатор НИКОГДА не принимается из тела запроса: иначе клиент
 *   назвался бы чужим аккаунтом канала и получил доступ к чужому
 *   кабинету (роут /api/bot/message вычисляет его из сессии);
 * - userId в нём — не секрет: это тот же идентификатор, по которому
 *   кабинет уже резолвит владельца данных, а не токен и не пароль.
 *
 * Идентификатор хранится как providerAccountId в ОБЩЕЙ OAuthAccount
 * (packages/core/src/bot/identity.ts): у канала и у сайта одна
 * учётная запись, второй стороны идентичностей в проекте нет.
 */
import { BOT_CHANNEL_LABELS, type BotChannel } from '@udgu/core';

/** Префикс демо-идентификатора: виден в кабинете и в аудите. */
export const DEMO_CHANNEL_ID_PREFIX = 'demo';

/**
 * Демо-идентификатор аккаунта канала для владельца сессии.
 *
 * Канал в имени — его собственное имя (telegram / vk / max), а не код
 * провайдера: идентификатор показывает и сотрудник деканата в аудите, и
 * студент в кабинете, и он должен читаться.
 */
export function demoChannelUserId(channel: BotChannel, userId: string): string {
  if (userId === '') {
    throw new Error('Демо-идентификатор канала требует userId.');
  }
  return `${DEMO_CHANNEL_ID_PREFIX}-${channel}-${userId}`;
}

/** Человекочитаемое название канала (BOT_CHANNEL_LABELS ядра). */
export function channelLabel(channel: BotChannel): string {
  return BOT_CHANNEL_LABELS[channel];
}
