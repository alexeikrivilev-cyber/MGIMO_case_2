/**
 * Единственная точка пакета, через которую домен обращается к базе.
 *
 * Архитектурное правило: сервисы packages/core не создают собственных
 * подключений и не читают DATABASE_URL — они берут клиент здесь.
 * Для тестов достаточно выставить DATABASE_URL на тестовую базу до
 * первого обращения: клиент создаётся лениво (см. @udgu/db/src/client.ts).
 *
 * Обратная зависимость (packages/db → @udgu/core) существует только
 * у сидера (prisma/seed.ts использует путь приватного хранилища) и
 * не входит в граф импортов точки входа @udgu/db, поэтому цикла
 * на этапе выполнения нет.
 */
import { getPrisma, type PrismaClient } from '@udgu/db';

/** Ленивый Prisma-клиент приложения. */
export function prisma(): PrismaClient {
  return getPrisma();
}

/**
 * Пространство имён Prisma (JsonNull/DbNull и типы) — реэкспорт из
 * пакета db, чтобы остальной код ядра не импортировал @udgu/db напрямую.
 */
export { Prisma } from '@udgu/db';
